// CreateSQL returns the DDL of a table: SHOW CREATE TABLE on MySQL, rebuilt
// from the catalog on PostgreSQL.
func (c *Conn) CreateSQL(ctx context.Context, schema, table string) (string, error) {
	if c.IsMySQL() {
		res, err := c.Query(ctx, "SHOW CREATE TABLE "+c.QT(schema, table))
		if err != nil {
			return "", err
		}
		if len(res.Rows) == 0 || len(res.Rows[0]) < 2 {
			return "", fmt.Errorf("no DDL for %s", table)
		}
		return res.Rows[0][1].Text, nil
	}
	cols, err := c.Columns(schema, table)
	if err != nil {
		return "", err
	}
	var b strings.Builder
	fmt.Fprintf(&b, "CREATE TABLE %s (\n", c.QT(schema, table))
	for i, col := range cols {
		fmt.Fprintf(&b, "  %s %s", c.Q(col.Name), col.Type)
		if !col.Nullable {
			b.WriteString(" NOT NULL")
		}
		if col.Default != "" && col.Extra == "" {
			b.WriteString(" DEFAULT " + col.Default)
		}
		if col.Extra == "identity" {
			b.WriteString(" GENERATED BY DEFAULT AS IDENTITY")
		}
		if i < len(cols)-1 {
			b.WriteString(",")
		}
		b.WriteString("\n")
	}
	rows, err := c.DB.QueryContext(ctx, `SELECT conname, pg_get_constraintdef(oid) FROM pg_constraint WHERE conrelid = $1::regclass ORDER BY contype, conname`, c.QT(schema, table))
	if err != nil {
		return "", err
	}
	defer rows.Close()
	for rows.Next() {
		var name, def string
		if err := rows.Scan(&name, &def); err != nil {
			return "", err
		}
		fmt.Fprintf(&b, "  ,CONSTRAINT %s %s\n", c.Q(name), def)
	}
	b.WriteString(");")
	ixs, err := c.Indexes(schema, table)
	if err != nil {
		return "", err
	}
	for _, ix := range ixs {
		if !strings.Contains(ix.Columns, "_pkey") && !strings.HasSuffix(ix.Name, "_pkey") && !strings.HasSuffix(ix.Name, "_key") {
			b.WriteString("\n" + ix.Columns + ";")
		}
	}
	return b.String(), nil
}

// ExportOptions mirror phpMyAdmin's: structure (CREATE), DROP before it, data.
type ExportOptions struct {
	Create, Drop, Data bool
}

// Export writes the selected statements for the tables (views are skipped)
// with INSERTs in batches of 200 rows. progress gets one line per table.
func (c *Conn) Export(ctx context.Context, schema string, tables []string, opt ExportOptions, w io.Writer, progress func(string)) error {
	bw := bufio.NewWriter(w)
	defer bw.Flush()
	fmt.Fprintf(bw, "-- hyprdb export of %s (%s) at %s\n\n", schema, c.Cfg.Kind.Label(), time.Now().Format(time.RFC3339))
	if c.IsMySQL() {
		fmt.Fprintln(bw, "SET FOREIGN_KEY_CHECKS=0;")
	}
	for _, t := range tables {
		if ctx.Err() != nil {
			return ctx.Err()
		}
		progress("exporting " + t)
		fmt.Fprintf(bw, "\n-- %s\n", t)
		if opt.Drop {
			fmt.Fprintf(bw, "DROP TABLE IF EXISTS %s;\n", c.QT(schema, t))
		}
		if opt.Create {
			ddl, err := c.CreateSQL(ctx, schema, t)
			if err != nil {
				return err
			}
			fmt.Fprintln(bw, strings.TrimSuffix(ddl, ";")+";")
		}
		if !opt.Data {
			continue
		}
		rows, err := c.DB.QueryContext(ctx, "SELECT * FROM "+c.QT(schema, t))
		if err != nil {
			return err
		}
		res, err := readRows(rows)
		rows.Close()
		if err != nil {
			return err
		}
		if len(res.Rows) == 0 {
			continue
		}
		cols := make([]string, len(res.Columns))
		for i, n := range res.Columns {
			cols[i] = c.Q(n)
		}
		head := fmt.Sprintf("INSERT INTO %s (%s) VALUES\n", c.QT(schema, t), strings.Join(cols, ", "))
		for i, row := range res.Rows {
			if i%200 == 0 {
				if i > 0 {
					bw.WriteString(";\n")
				}
				bw.WriteString(head)
			} else {
				bw.WriteString(",\n")
			}
			bw.WriteString("(")
			for j, v := range row {
				if j > 0 {
					bw.WriteString(", ")
				}
				bw.WriteString(c.literal(v, res.Types[j]))
			}
			bw.WriteString(")")
		}
		bw.WriteString(";\n")
	}
	if c.IsMySQL() {
		fmt.Fprintln(bw, "\nSET FOREIGN_KEY_CHECKS=1;")
	}
	return bw.Flush()
}

func (c *Conn) literal(v Value, typ string) string {
	if v.Null {
		return "NULL"
	}
	t := strings.ToUpper(typ)
	if strings.Contains(t, "BLOB") || strings.Contains(t, "BINARY") || t == "BYTEA" {
		if c.IsMySQL() {
			return "X'" + hex.EncodeToString([]byte(v.Text)) + "'"
		}
		return `'\x` + hex.EncodeToString([]byte(v.Text)) + "'"
	}
	if c.IsMySQL() {
		return "'" + strings.NewReplacer(`\`, `\\`, `'`, `\'`, "\x00", `\0`).Replace(v.Text) + "'"
	}
	if strings.Contains(v.Text, `\`) {
		return "E'" + strings.NewReplacer(`\`, `\\`, `'`, `''`).Replace(v.Text) + "'"
	}
	return "'" + strings.ReplaceAll(v.Text, `'`, `''`) + "'"
}

// Import executes every statement of a .sql script in order. progress is
// called with the statement count after each one.
func (c *Conn) Import(ctx context.Context, r io.Reader, progress func(n int)) (int, error) {
	data, err := io.ReadAll(r)
	if err != nil {
		return 0, err
	}
	n := 0
	for _, stmt := range SplitStatements(string(data)) {
		if ctx.Err() != nil {
			return n, ctx.Err()
		}
		if _, err := c.DB.ExecContext(ctx, stmt); err != nil {
			return n, fmt.Errorf("statement %d: %w\n%s", n+1, err, abbreviate(stmt))
		}
		n++
		progress(n)
	}
	return n, nil
}

func abbreviate(s string) string {
	if len(s) > 200 {
		return s[:200] + "…"
	}
	return s
}

// SplitStatements splits a script on its delimiter, honouring quotes,
// comments, dollar quoting and the mysql client's DELIMITER directive.
func SplitStatements(script string) []string {
	var out []string
	var cur strings.Builder
	delim := ";"
	flush := func() {
		if s := strings.TrimSpace(cur.String()); s != "" {
			out = append(out, s)
		}
		cur.Reset()
	}
	i := 0
	for i < len(script) {
		rest := script[i:]
		// DELIMITER directive at line start.
		if strings.TrimSpace(cur.String()) == "" {
			if l := strings.ToUpper(rest); strings.HasPrefix(l, "DELIMITER ") {
				end := strings.IndexByte(rest, '\n')
				if end < 0 {
					end = len(rest)
				}
				delim = strings.TrimSpace(rest[len("DELIMITER "):end])
				i += end + 1
				continue
			}
		}
		if strings.HasPrefix(rest, delim) {
			flush()
			i += len(delim)
			continue
		}
		switch {
		case strings.HasPrefix(rest, "--") || (rest[0] == '#' && delim == ";"):
			end := strings.IndexByte(rest, '\n')
			if end < 0 {
				end = len(rest)
			}
			i += end
		case strings.HasPrefix(rest, "/*") && !strings.HasPrefix(rest, "/*!"):
			end := strings.Index(rest, "*/")
			if end < 0 {
				end = len(rest) - 2
			}
			i += end + 2
		case rest[0] == '\'' || rest[0] == '"' || rest[0] == '`':
			n := quoted(rest, rest[0])
			cur.WriteString(rest[:n])
			i += n
		case rest[0] == '$':
			// $$ or $tag$ dollar quoting (PostgreSQL).
			end := strings.IndexByte(rest[1:], '$')
			if end >= 0 && isTag(rest[1:end+1]) {
				tag := rest[:end+2]
				close := strings.Index(rest[len(tag):], tag)
				n := len(rest)
				if close >= 0 {
					n = len(tag) + close + len(tag)
				}
				cur.WriteString(rest[:n])
				i += n
			} else {
				cur.WriteByte('$')
				i++
			}
		default:
			cur.WriteByte(rest[0])
			i++
		}
	}
	flush()
	return out
}

func isTag(s string) bool {
	for _, r := range s {
		if !(r == '_' || r >= 'a' && r <= 'z' || r >= 'A' && r <= 'Z' || r >= '0' && r <= '9') {
			return false
		}
	}
	return true
}

// quoted returns the length of the quoted literal starting at s[0].
func quoted(s string, q byte) int {
	for i := 1; i < len(s); i++ {
		switch s[i] {
		case '\\':
			i++
		case q:
			if i+1 < len(s) && s[i+1] == q {
				i++
				continue
			}
			return i + 1
		}
	}
	return len(s)
}
